import { COLOR_KEYS, ROLE_KEYS, SCALE_STEPS, type ColorRef, type Guide } from "../model/types";
import { buildScales } from "../lib/color";
import { buildTypeScale } from "../lib/typeScale";

// W3C Design Tokens Community Group format (2025.10 spec): https://www.designtokens.org/tr/drafts/format/

const px = (value: number) => ({ value, unit: "px" });

function refAlias(ref: ColorRef): string {
  if (ref === "white" || ref === "black") return `{color.base.${ref}}`;
  const i = ref.lastIndexOf("-");
  return `{color.${ref.slice(0, i)}.${ref.slice(i + 1)}}`;
}

function opacityHex(opacity: number): string {
  return Math.round(opacity * 255)
    .toString(16)
    .padStart(2, "0");
}

export function buildDtcg(guide: Guide) {
  const scales = buildScales(guide.colors);
  const type = buildTypeScale(guide.typography);
  const t = guide.typography;
  const l = guide.layout;

  const color: Record<string, unknown> = {
    $type: "color",
    base: { white: { $value: "#ffffff" }, black: { $value: "#000000" } },
  };
  for (const key of COLOR_KEYS) {
    color[key] = Object.fromEntries(SCALE_STEPS.map((s) => [s, { $value: scales[key][s] }]));
  }

  const role = Object.fromEntries(
    (["light", "dark"] as const).map((mode) => [
      mode,
      Object.fromEntries(
        ROLE_KEYS.map((r) => [
          r,
          { $type: "color", $value: refAlias(guide.colors.roles[mode][r]) },
        ]),
      ),
    ]),
  );

  const families = { heading: t.heading, body: t.body, mono: t.mono };

  return {
    $description: `${guide.basics.name} design tokens, generated by Styleguide Generator.`,
    color,
    role,
    font: {
      family: Object.fromEntries(
        Object.entries(families).map(([k, f]) => [
          k,
          {
            $type: "fontFamily",
            $value: [f.name, ...f.fallback.split(",").map((s) => s.trim().replace(/^'|'$/g, ""))],
          },
        ]),
      ),
    },
    typography: Object.fromEntries(
      Object.entries(type).map(([k, s]) => [
        k,
        {
          $type: "typography",
          $value: {
            fontFamily: k.endsWith("xl") ? "{font.family.heading}" : "{font.family.body}",
            fontSize: px(s.size),
            fontWeight: s.weight,
            letterSpacing: { value: s.letterSpacing, unit: "em" },
            lineHeight: s.lineHeight,
          },
        },
      ]),
    ),
    space: {
      $type: "dimension",
      ...Object.fromEntries(l.spacingScale.map((m) => [m, { $value: px(m * l.spacingBase) }])),
    },
    radius: {
      $type: "dimension",
      ...Object.fromEntries(Object.entries(l.radius).map(([k, v]) => [k, { $value: px(v) }])),
    },
    shadow: Object.fromEntries(
      Object.entries(l.shadow).map(([k, s]) => [
        k,
        {
          $type: "shadow",
          $value: {
            color: `#000000${opacityHex(s.opacity)}`,
            offsetX: px(0),
            offsetY: px(s.y),
            blur: px(s.blur),
            spread: px(s.spread),
          },
        },
      ]),
    ),
    duration: {
      $type: "duration",
      ...Object.fromEntries(
        Object.entries(l.duration).map(([k, v]) => [k, { $value: { value: v, unit: "ms" } }]),
      ),
    },
    easing: {
      $type: "cubicBezier",
      ...Object.fromEntries(Object.entries(l.easing).map(([k, v]) => [k, { $value: v }])),
    },
    breakpoint: {
      $type: "dimension",
      ...Object.fromEntries(Object.entries(l.breakpoints).map(([k, v]) => [k, { $value: px(v) }])),
    },
  };
}

export function generateDtcg(guide: Guide): string {
  return JSON.stringify(buildDtcg(guide), null, 2) + "\n";
}
