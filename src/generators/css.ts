import type { Guide } from "../model/types";
import { baseVars, commentSafe, roleVars, type Var } from "../lib/tokens";

export function block(selector: string, vars: Var[], indent = ""): string {
  const body = vars.map(([k, v]) => `${indent}  ${k}: ${v};`).join("\n");
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

/** Dark-mode role overrides: explicit [data-theme="dark"], or the OS preference unless light is forced. */
export function darkBlocks(guide: Guide): string {
  const dark = roleVars(guide, "dark");
  return [
    block('[data-theme="dark"]', dark),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, "  ")}\n}`,
  ].join("\n\n");
}

export function generateCss(guide: Guide): string {
  return [
    `/* ${commentSafe(guide.basics.name)} design tokens. Generated by Styleguide Generator; see STYLEGUIDE.md. */`,
    block(":root", [...baseVars(guide), ...roleVars(guide, "light")]),
    darkBlocks(guide),
    "",
  ].join("\n\n");
}
