import { COLOR_KEYS, ROLE_KEYS, SCALE_STEPS, type Guide } from "../model/types";
import { buildScales } from "../lib/color";
import { buildTypeScale } from "../lib/typeScale";
import {
  baseVars,
  commentSafe,
  fontStack,
  kebab,
  rem,
  roleVar,
  roleVars,
  shadowCss,
  easingCss,
} from "../lib/tokens";
import { block, darkBlocks } from "./css";

/**
 * Tailwind v4: a self-contained CSS entry. Theme variables use Tailwind's own namespaces, so
 * `bg-primary`, `text-text-muted`, `font-heading`, `text-xl`, `rounded-md`, `shadow-md` and
 * `ease-standard` work directly. Durations stay plain variables because v4 has no theme key for them.
 */
export function generateTailwindV4(guide: Guide): string {
  const all = baseVars(guide);
  const vars = all.filter(([k]) => !k.startsWith("--space-") && !k.startsWith("--duration-"));
  const durations = all.filter(([k]) => k.startsWith("--duration-"));
  return [
    `/* ${commentSafe(guide.basics.name)} Tailwind v4 theme. Generated by Styleguide Generator; see STYLEGUIDE.md. */`,
    '@import "tailwindcss";',
    '@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));',
    block("@theme", [
      ["--spacing", rem(guide.layout.spacingBase)],
      ...vars,
      ...roleVars(guide, "light"),
    ]),
    block(":root", durations),
    darkBlocks(guide),
    "",
  ].join("\n\n");
}

/** Tailwind v3: a config file. Role colors read the CSS variables, so tokens.css must be loaded too. */
export function generateTailwindV3(guide: Guide): string {
  const scales = buildScales(guide.colors);
  const type = buildTypeScale(guide.typography);
  const l = guide.layout;
  const colors: Record<string, unknown> = {};
  for (const key of COLOR_KEYS) {
    colors[key] = Object.fromEntries(SCALE_STEPS.map((s) => [s, scales[key][s]]));
  }
  // Role names that clash with a palette name (primary, success...) go under `role`.
  colors.role = Object.fromEntries(ROLE_KEYS.map((r) => [kebab(r), `var(${roleVar(r)})`]));
  const theme = {
    colors: colors,
    fontFamily: {
      heading: fontStack(guide.typography.heading),
      body: fontStack(guide.typography.body),
      mono: fontStack(guide.typography.mono),
    },
    fontSize: Object.fromEntries(
      Object.entries(type).map(([k, s]) => [
        k,
        [
          rem(s.size),
          {
            lineHeight: String(s.lineHeight),
            letterSpacing: `${s.letterSpacing}em`,
            fontWeight: String(s.weight),
          },
        ],
      ]),
    ),
    spacing: Object.fromEntries(l.spacingScale.map((m) => [m, rem(m * l.spacingBase)])),
    borderRadius: Object.fromEntries(Object.entries(l.radius).map(([k, v]) => [k, `${v}px`])),
    boxShadow: Object.fromEntries(Object.entries(l.shadow).map(([k, v]) => [k, shadowCss(v)])),
    transitionDuration: Object.fromEntries(
      Object.entries(l.duration).map(([k, v]) => [k, `${v}ms`]),
    ),
    transitionTimingFunction: Object.fromEntries(
      Object.entries(l.easing).map(([k, v]) => [k, easingCss(v)]),
    ),
    screens: Object.fromEntries(Object.entries(l.breakpoints).map(([k, v]) => [k, `${v}px`])),
  };
  return [
    `// ${commentSafe(guide.basics.name)} Tailwind v3 config. Generated by Styleguide Generator; see STYLEGUIDE.md.`,
    "// Role colors (colors.role.*) use CSS variables: also load tokens.css.",
    "/** @type {import('tailwindcss').Config} */",
    `export default ${JSON.stringify({ darkMode: ["selector", '[data-theme="dark"]'], theme: { extend: theme } }, null, 2)};`,
    "",
  ].join("\n");
}

export function generateTailwind(guide: Guide): string {
  return guide.outputs.tailwind === "v3" ? generateTailwindV3(guide) : generateTailwindV4(guide);
}

export function tailwindFileName(guide: Guide): string {
  return guide.outputs.tailwind === "v3" ? "tailwind.config.js" : "tailwind.css";
}
